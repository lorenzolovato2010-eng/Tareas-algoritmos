# 1. Realizar un programa que lea cuatro valores numéricos e informar su suma y promedio.

num1=int(input("Ingrese primer valor:"))
num2=int(input("Ingrese segundo valor:"))
num3=int(input("Ingrese tercer valor:"))
num4=int(input("Ingrese cuarto valor:"))
suma=num1+num2+num3+num4
prom=(num1+num2+num3+num4)/4
print("La suma de los cuatro valores es:")
print(suma)
print("El promedio de los cuatro valores es:")
print(prom)